import Database from 'better-sqlite3';
import path from 'path';
import { fileURLToPath } from 'url';
import { closeNeonDatabase, getNeonPool, initializeNeonDatabase } from '../config/neonDatabase.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const quoteIdentifier = (identifier) => {
  if (typeof identifier !== 'string' || !/^[A-Za-z_][A-Za-z0-9_]*$/.test(identifier)) {
    throw new Error(`Unsupported SQLite identifier: ${String(identifier)}`);
  }
  return `"${identifier}"`;
};

export const convertSQLiteDdlToPostgres = (ddl) => ddl
  .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/\bINTEGER\b/gi, 'BIGINT')
  .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
  .replace(/\bBLOB\b/gi, 'BYTEA')
  .replace(/\bDEFAULT\s+CURRENT_TIMESTAMP\b/gi, 'DEFAULT CURRENT_TIMESTAMP::text');

const getCreationOrder = (tables) => {
  const pending = new Map(tables.map(table => [table.name, table]));
  const created = new Set();
  const ordered = [];

  while (pending.size > 0) {
    let progressed = false;

    for (const [name, table] of pending) {
      const dependencies = [...table.sql.matchAll(/\bREFERENCES\s+["`]?([A-Za-z_][A-Za-z0-9_]*)["`]?/gi)]
        .map(match => match[1])
        .filter(dependency => dependency !== name && pending.has(dependency));

      if (dependencies.every(dependency => created.has(dependency))) {
        ordered.push(table);
        created.add(name);
        pending.delete(name);
        progressed = true;
      }
    }

    if (!progressed) {
      throw new Error(`Could not order SQLite tables with foreign-key dependencies: ${[...pending.keys()].join(', ')}`);
    }
  }

  return ordered;
};

const copyTableData = async (source, client, tableName) => {
  const table = quoteIdentifier(tableName);
  const columns = source.prepare(`PRAGMA table_info(${table})`).all().map(column => column.name);
  if (columns.length === 0) {
    throw new Error(`SQLite table has no columns: ${tableName}`);
  }

  const columnList = columns.map(column => quoteIdentifier(column.toLowerCase())).join(', ');
  const rowsPerBatch = Math.max(1, Math.min(500, Math.floor(60000 / columns.length)));
  let batch = [];
  let rowCount = 0;

  const insertBatch = async () => {
    if (batch.length === 0) return;
    const values = [];
    const valueExpressions = batch.map((row, rowIndex) => {
      const offset = rowIndex * columns.length;
      values.push(...row);
      return `(${columns.map((_, columnIndex) => `$${offset + columnIndex + 1}`).join(', ')})`;
    });

    await client.query(
      `INSERT INTO ${table} (${columnList}) VALUES ${valueExpressions.join(', ')}`,
      values
    );
    rowCount += batch.length;
    batch = [];
  };

  for (const row of source.prepare(`SELECT ${columnList} FROM ${table}`).iterate()) {
    batch.push(columns.map(column => row[column]));
    if (batch.length >= rowsPerBatch) await insertBatch();
  }
  await insertBatch();

  const identityColumn = source.prepare(`PRAGMA table_info(${table})`).all()
    .find(column => column.pk === 1 && /INTEGER/i.test(column.type));
  if (identityColumn && rowCount > 0) {
    const sequence = await client.query(
      'SELECT pg_get_serial_sequence($1, $2) AS sequence',
      [tableName, identityColumn.name.toLowerCase()]
    );
    if (sequence.rows[0]?.sequence) {
      const maxValue = await client.query(
        `SELECT MAX(${quoteIdentifier(identityColumn.name.toLowerCase())}) AS value FROM ${table}`
      );
      await client.query(
        'SELECT setval($1::regclass, $2, true)',
        [sequence.rows[0].sequence, maxValue.rows[0].value]
      );
    }
  }

  return rowCount;
};

const migrate = async () => {
  const databaseFile = process.env.DB_PATH
    ? path.resolve(process.env.DB_PATH)
    : path.resolve(__dirname, '../database_files/redsea_brokerage.db');

  const source = new Database(databaseFile, { readonly: true, fileMustExist: true });
  let neonInitialized = false;

  try {
    await initializeNeonDatabase();
    neonInitialized = true;
    const pool = getNeonPool();
    const existingTables = await pool.query(`
      SELECT table_name
      FROM information_schema.tables
      WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
    `);
    if (existingTables.rowCount > 0) {
      throw new Error(
        `Neon database is not empty (${existingTables.rowCount} public tables found). ` +
        'Use a new empty Neon database; this importer never overwrites existing tables.'
      );
    }

    const tables = source.prepare(`
      SELECT name, sql
      FROM sqlite_master
      WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND sql IS NOT NULL
      ORDER BY name
    `).all();
    const indexes = source.prepare(`
      SELECT sql
      FROM sqlite_master
      WHERE type = 'index' AND sql IS NOT NULL
      ORDER BY name
    `).all();

    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      for (const table of getCreationOrder(tables)) {
        await client.query(convertSQLiteDdlToPostgres(table.sql));
      }

      let totalRows = 0;
      for (const table of tables) {
        const copied = await copyTableData(source, client, table.name);
        totalRows += copied;
        console.log(`   Copied ${copied} rows from ${table.name}`);
      }

      for (const index of indexes) {
        await client.query(convertSQLiteDdlToPostgres(index.sql));
      }

      await client.query('COMMIT');
      console.log(`✅ Imported ${tables.length} SQLite tables and ${totalRows} rows into Neon`);
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
  } finally {
    source.close();
    if (neonInitialized) await closeNeonDatabase();
  }
};

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  migrate().catch(error => {
    console.error('❌ SQLite-to-Neon migration failed:', error.message);
    process.exitCode = 1;
  });
}
