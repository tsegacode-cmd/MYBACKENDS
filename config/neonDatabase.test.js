import test from 'node:test';
import assert from 'node:assert/strict';
import { toPostgresPlaceholders } from './neonDatabase.js';
import { convertSQLiteDdlToPostgres } from '../scripts/migrateSqliteToNeon.js';

test('converts positional placeholders to PostgreSQL format', () => {
  assert.equal(
    toPostgresPlaceholders('SELECT * FROM users WHERE username = ? AND role = ?'),
    'SELECT * FROM users WHERE username = $1 AND role = $2'
  );
});

test('leaves question marks in literals, identifiers, and comments unchanged', () => {
  assert.equal(
    toPostgresPlaceholders(`SELECT '?' AS literal, "question?" FROM users -- ?\nWHERE id = ? /* ? */`),
    `SELECT '?' AS literal, "question?" FROM users -- ?\nWHERE id = $1 /* ? */`
  );
});

test('handles escaped quotes while converting placeholders', () => {
  assert.equal(
    toPostgresPlaceholders("SELECT 'it''s ?' WHERE email = ?"),
    "SELECT 'it''s ?' WHERE email = $1"
  );
});

test('converts SQLite identity and timestamp defaults to PostgreSQL syntax', () => {
  assert.equal(
    convertSQLiteDdlToPostgres(
      'CREATE TABLE users (_id INTEGER PRIMARY KEY AUTOINCREMENT, count INTEGER, amount REAL, data BLOB, created_at TEXT DEFAULT CURRENT_TIMESTAMP)'
    ),
    'CREATE TABLE users (_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, count BIGINT, amount DOUBLE PRECISION, data BYTEA, created_at TEXT DEFAULT CURRENT_TIMESTAMP::text)'
  );
});
